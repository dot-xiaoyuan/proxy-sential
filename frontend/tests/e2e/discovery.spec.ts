import {test,expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
for(const width of [390,1280,1440])test(`discovery layout ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:width===390?844:width===1280?800:900})
 await page.goto('/discovery?router_include_candidates=true&router_role=')
 await expect(page).toHaveURL(/tab=discovery/)
 await expect(page.getByRole('heading',{name:'发现设备',level:1})).toBeVisible()
 const printer=page.getByRole('row').filter({hasText:'00:11:22:33:44:55'})
 await expect(printer).toContainText('192.0.2.10')
 await expect(printer).toContainText('HP LaserJet Pro MFP')
 await expect(printer).toContainText('打印机')
 await expect(page.getByText('fe80::20c:29ff:fe00:20',{exact:true}).filter({visible:true})).toBeVisible()
 const probe=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+2,controls:[...document.querySelectorAll('.passive-ledger-table .ant-btn')].map(e=>({wrap:getComputedStyle(e).whiteSpace,shrink:getComputedStyle(e).flexShrink}))}))
 expect(probe.overflow).toBe(false);expect(probe.controls.length).toBeGreaterThan(0);expect(probe.controls.every(c=>c.wrap==='nowrap'&&c.shrink==='0')).toBe(true)
 await writeFile(info.outputPath('dom.json'),JSON.stringify(probe,null,2));await page.screenshot({path:info.outputPath('discovery.png')})
 await printer.getByRole('button',{name:'查看详情'}).click()
 await expect(page.getByRole('dialog')).toContainText('DNS-SD')
 await page.getByRole('button',{name:'Close'}).click()
 await page.goto('/discovery?tab=routers')
 await expect(page).toHaveURL(/tab=network/)
 await expect(page.getByRole('heading',{name:'路由器',level:1})).toBeVisible()
 await page.goto('/discovery/routers/router-expired-82')
 await expect(page.getByRole('heading',{name:'历史路由观察'})).toBeVisible()
 const detailProbe=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+2,controls:[...document.querySelectorAll('.router-detail-page .ant-tag')].map(e=>({wrap:getComputedStyle(e).whiteSpace,shrink:getComputedStyle(e).flexShrink}))}))
 expect(detailProbe.overflow).toBe(false);expect(detailProbe.controls.every(c=>c.wrap==='nowrap'&&c.shrink==='0')).toBe(true)
 await writeFile(info.outputPath('router-detail-dom.json'),JSON.stringify(detailProbe,null,2));await page.screenshot({path:info.outputPath('router-detail.png'),fullPage:true})
 await page.goBack();await expect(page.getByRole('heading',{name:'路由器',level:1})).toBeVisible()
 await page.goto('/settings/sources?tab=scan');await expect(page.getByText('默认关闭，只探测配置范围内的地址')).toBeVisible()
 await page.getByRole('button',{name:'新增探测配置'}).click();await expect(page.getByRole('button',{name:'确 定'})).toBeDisabled()
})
for(const width of [390,1280,1440])test(`expired router detail ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:width===390?844:width===1280?800:900})
 await page.goto('/discovery/routers/router-expired-82')
 await expect(page.getByRole('heading',{name:'历史路由观察'})).toBeVisible()
 await expect(page.getByText('该观察已失效',{exact:true})).toBeVisible()
 await expect(page.locator('.router-detail-header')).not.toContainText('85 分')
 await expect(page.locator('.ant-progress')).toHaveCount(0)
 const probe=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+2,collapsed:!document.querySelector('details.router-historical-score')?.hasAttribute('open'),controls:[...document.querySelectorAll('.router-detail-page .ant-tag,.router-detail-page .ant-btn')].map(e=>({wrap:getComputedStyle(e).whiteSpace,shrink:getComputedStyle(e).flexShrink}))}))
 expect(probe.overflow).toBe(false);expect(probe.collapsed).toBe(true);expect(probe.controls.every(c=>c.wrap==='nowrap'&&c.shrink==='0')).toBe(true)
 await writeFile(info.outputPath('expired-dom.json'),JSON.stringify(probe,null,2));await page.screenshot({path:info.outputPath('expired-router.png'),fullPage:true})
 await page.getByText('查看历史分数（85 分）',{exact:true}).click()
 await expect(page.getByText('证据 expired-gateway-role-82',{exact:true})).toBeVisible()
 await expect(page.getByText('支持窗口已失效',{exact:true})).toBeVisible()
 await page.screenshot({path:info.outputPath('expired-router-expanded.png'),fullPage:true})
})
