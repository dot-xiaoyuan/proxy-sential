//go:build ignore

// Run with: go run scripts/generate-router-bpf.go
// tcpdump compiles the configured discovery filter for Ethernet frames.
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"proxy-sentinel/internal/discovery"
)

func main() {
	file, err := os.CreateTemp("", "proxy-sentinel-empty-*.pcap")
	if err != nil {
		panic(err)
	}
	defer os.Remove(file.Name())
	header := make([]byte, 24)
	binary.LittleEndian.PutUint32(header, 0xa1b2c3d4)
	binary.LittleEndian.PutUint16(header[4:], 2)
	binary.LittleEndian.PutUint16(header[6:], 4)
	binary.LittleEndian.PutUint32(header[16:], 65535)
	binary.LittleEndian.PutUint32(header[20:], 1)
	if _, err = file.Write(header); err != nil {
		panic(err)
	}
	if err = file.Close(); err != nil {
		panic(err)
	}
	raw, err := exec.Command("tcpdump", "-ddd", "-r", file.Name(), discovery.DiscoveryCaptureFilter()).Output()
	if err != nil {
		panic(err)
	}
	lines := strings.Fields(string(raw))
	if len(lines) < 5 {
		panic("tcpdump returned no BPF instructions")
	}
	var count int
	if _, err = fmt.Sscan(lines[0], &count); err != nil || count <= 0 || len(lines) != 1+4*count {
		panic("invalid tcpdump -ddd output")
	}
	var body bytes.Buffer
	fmt.Fprintln(&body, "//go:build linux")
	fmt.Fprintln(&body, "\npackage devicesignal\n\nimport \"syscall\"")
	fmt.Fprintln(&body, "// Generated by go run scripts/generate-router-bpf.go from discovery.DiscoveryCaptureFilter().")
	fmt.Fprintln(&body, "var routerProtocolSocketFilter = []syscall.SockFilter{")
	for index := 0; index < count; index++ {
		base := 1 + index*4
		fmt.Fprintf(&body, "{Code:%s, Jt:%s, Jf:%s, K:%s},\n", lines[base], lines[base+1], lines[base+2], lines[base+3])
	}
	fmt.Fprintln(&body, "}\n\nfunc attachRouterProtocolFilter(fd int) error { return syscall.AttachLsf(fd, routerProtocolSocketFilter) }")
	formatted, err := format.Source(body.Bytes())
	if err != nil {
		panic(err)
	}
	path := filepath.Join("internal", "devicesignal", "router_filter_linux.go")
	if err = os.WriteFile(path, formatted, 0644); err != nil {
		panic(err)
	}
}
